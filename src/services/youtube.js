const STORAGE_KEY = 'shunya_youtube_videos_v1';
const API_KEY_STORAGE = 'shunya_youtube_api_key';

/**
 * Get all videos (from localStorage or initial list)
 */
export function getSavedVideos() {
  if (typeof window === 'undefined') return INITIAL_CHANNEL_VIDEOS;
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (e) {
    console.warn('Error reading cached videos:', e);
  }
  return INITIAL_CHANNEL_VIDEOS;
}

/**
 * Save videos to localStorage
 */
export function saveVideos(videos) {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(videos));
  } catch (e) {
    console.warn('Error saving videos:', e);
  }
}

/**
 * Extract YouTube Video ID from any URL or return ID directly
 */
export function extractYouTubeId(urlOrId) {
  if (!urlOrId) return null;
  const str = urlOrId.trim();
  if (/^[a-zA-Z0-9_-]{11}$/.test(str)) {
    return str;
  }
  const match = str.match(/(?:youtu\.be\/|youtube\.com\/(?:watch\?v=|embed\/|v\/|shorts\/))([a-zA-Z0-9_-]{11})/);
  return match ? match[1] : null;
}

