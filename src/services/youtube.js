/**
 * Add a video to the list dynamically (saves to localStorage)
 */
export async function addVideoToList(urlOrId, category = 'ताजा खबर') {
  const vid = extractYouTubeId(urlOrId);
  if (!vid) throw new Error('अमान्य YouTube लिंक या ID');

  const details = await fetchVideoDetails(vid);
  if (category) details.category = category;

  const current = getSavedVideos();
  // Filter out if duplicate, add to top
  const updated = [details, ...current.filter((v) => v.id !== vid)];
  saveVideos(updated);
  return updated;
}

/**
 * Fetch latest videos via YouTube Data API v3 if API key is provided
 */
export async function syncWithYouTubeAPI(apiKey) {
  const key = apiKey || (typeof window !== 'undefined' ? localStorage.getItem(API_KEY_STORAGE) : null) || import.meta.env.VITE_YOUTUBE_API_KEY;
  if (!key) return null;

  try {
    const url = `https://www.googleapis.com/youtube/v3/playlistItems?part=snippet&playlistId=${YOUTUBE_UPLOADS_PLAYLIST_ID}&maxResults=15&key=${key}`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`YouTube API returned status: ${res.status}`);
    const data = await res.json();

    if (data.items && data.items.length > 0) {
      const fetched = data.items.map((item) => {
        const vid = item.snippet.resourceId.videoId;
        const pubDate = new Date(item.snippet.publishedAt);
        return {
          id: vid,
          title: item.snippet.title,
          thumbnail: item.snippet.thumbnails?.high?.url || `https://i.ytimg.com/vi/${vid}/hqdefault.jpg`,
          category: 'ताजा अपलोड',
          date: pubDate.toLocaleDateString('hi-IN', { day: 'numeric', month: 'long', year: 'numeric' }),
          timeAgo: 'यूट्यूब सिंक',
          duration: 'बुलेटिन'
        };
      });
      saveVideos(fetched);
      return fetched;
    }
  } catch (err) {
    console.warn('YouTube API sync failed:', err);
    throw err;
  }
  return null;
}

/**
 * Returns YouTube Embed URL
 * If isAutoPlaylist is true, it embeds the channel's official Uploads Playlist (UU-fgtjMgE3GzSgkhxyi2kcQ),
 * which ALWAYS automatically plays the newest uploaded video without needing any code changes!
 */
export function getPlayerEmbedUrl(videoId, isAutoPlaylist = false) {
  if (isAutoPlaylist || !videoId) {
    return `https://www.youtube.com/embed/videoseries?list=${YOUTUBE_UPLOADS_PLAYLIST_ID}&rel=0`;
  }
  return `https://www.youtube.com/embed/${videoId}?autoplay=1&rel=0`;
}
